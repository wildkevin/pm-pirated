import { _electron as electron, expect, test, type Page } from '@playwright/test'
import { mkdtemp, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

async function openShortcuts(page: Page) {
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('tab', { name: 'Shortcuts', exact: true }).click()
}
async function edit(page: Page, label: string, key: string) {
  await page.getByRole('button', { name: `Edit shortcut for ${label}`, exact: true }).click()
  const input = page.getByLabel(`Shortcut for ${label}`, { exact: true })
  await input.press(key)
  await input.press('Enter')
}

test('editable shortcuts reject conflicts, update commands immediately, persist, clear and reset', async () => {
  const root = await mkdtemp(join(tmpdir(), 'pm-shortcuts-'))
  const userData = join(root, 'appdata')
  const launch = () => electron.launch({ args: ['.'], env: { ...process.env, PM_LOCAL_USER_DATA: userData } })
  let app = await launch()
  try {
    let page = await app.firstWindow()
    await app.evaluate(({ dialog }, dir) => { dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [dir] })) as typeof dialog.showOpenDialog }, root)
    await page.getByRole('button', { name: 'Open an existing workspace folder…' }).click()
    await expect(page.getByRole('button', { name: 'Create new', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'New request tab', exact: true }).click()
    await openShortcuts(page)
    await page.getByRole('button', { name: 'Edit shortcut for Close Tab', exact: true }).click()
    const input = page.getByLabel('Shortcut for Close Tab', { exact: true })
    await input.press('ControlOrMeta+q')
    await expect(page.getByRole('alert')).toContainText('reserved')
    await input.press('ControlOrMeta+s')
    await expect(page.getByRole('alert')).toContainText('Already assigned to Save Request')
    await input.press('Enter')
    await expect(input).toBeVisible()
    await input.press('Escape')
    await expect(page.getByRole('dialog', { name: 'SETTINGS' })).toBeVisible()
    await edit(page, 'Close Tab', 'ControlOrMeta+Alt+Shift+w')
    await expect.poll(async () => JSON.parse(await readFile(join(userData, 'settings.json'), 'utf8')).shortcutBindings.closeTab).toBe('Mod+Alt+Shift+KeyW')
    await page.screenshot({ path: '.qa/shortcuts-editable.png' })
    await page.keyboard.press('Escape')
    await page.keyboard.press('ControlOrMeta+w')
    await expect(page.locator('.tabs .tab')).toHaveCount(1)
    await page.keyboard.press('ControlOrMeta+Alt+Shift+w')
    await expect(page.locator('.tabs .tab')).toHaveCount(0)
    await page.keyboard.press('ControlOrMeta+Shift+t')
    await expect(page.locator('.tabs .tab')).toHaveCount(1)
    await app.close()
    app = await launch()
    page = await app.firstWindow()
    await expect(page.locator('.tabs .tab')).toHaveCount(1)
    await page.keyboard.press('ControlOrMeta+w')
    await expect(page.locator('.tabs .tab')).toHaveCount(1)
    await page.keyboard.press('ControlOrMeta+Alt+Shift+w')
    await expect(page.locator('.tabs .tab')).toHaveCount(0)
    await openShortcuts(page)
    await page.getByRole('button', { name: 'Reset shortcut for Close Tab', exact: true }).click()
    await expect.poll(async () => JSON.parse(await readFile(join(userData, 'settings.json'), 'utf8')).shortcutBindings.closeTab).toBe('Mod+KeyW')
    await edit(page, 'New Request Tab', 'Backspace')
    await page.keyboard.press('Escape')
    await page.keyboard.press('ControlOrMeta+t')
    await expect(page.locator('.tabs .tab')).toHaveCount(0)
    await openShortcuts(page)
    await page.getByRole('button', { name: 'Restore Defaults', exact: true }).click()
    await page.getByRole('switch', { name: 'Keyboard Shortcuts', exact: true }).click()
    await page.keyboard.press('Escape')
    await page.keyboard.press('ControlOrMeta+t')
    await expect(page.locator('.tabs .tab')).toHaveCount(0)
    await openShortcuts(page)
    await page.getByRole('switch', { name: 'Keyboard Shortcuts', exact: true }).click()
    await page.keyboard.press('Escape')
    await page.keyboard.press('ControlOrMeta+t')
    await expect(page.locator('.tabs .tab')).toHaveCount(1)
    await page.keyboard.press('ControlOrMeta+w')
    await expect(page.locator('.tabs .tab')).toHaveCount(0)
  } finally { await app.close() }
})

test('Save As, layout and zoom shortcuts honor custom bindings even inside editors', async () => {
  const root = await mkdtemp(join(tmpdir(), 'pm-shortcut-actions-'))
  const launch = () => electron.launch({ args: ['.'], env: { ...process.env, PM_LOCAL_USER_DATA: join(root, 'appdata') } })
  let app = await launch()
  try {
    let page = await app.firstWindow()
    await app.evaluate(({ dialog }, dir) => { dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [dir] })) as typeof dialog.showOpenDialog }, root)
    await page.getByRole('button', { name: 'Open an existing workspace folder…' }).click()
    await expect(page.getByRole('button', { name: 'Create new', exact: true })).toBeVisible()
    await page.evaluate(async () => { const { id } = await window.api.createCollection('Saved'); await window.api.createRequest(id, 'Existing request') })
    await app.close(); app = await launch(); page = await app.firstWindow()
    await page.getByRole('treeitem').filter({ hasText: 'Saved' }).first().dblclick()
    await page.getByRole('treeitem').filter({ hasText: 'Existing request' }).last().dblclick()
    await page.getByLabel('Request URL').fill('https://example.test/saved')
    await page.keyboard.press('ControlOrMeta+s')
    await expect(page.locator('.tabs .tab-dirty')).toHaveCount(0)
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await expect.poll(async () => JSON.parse(await readFile(join(root, 'collections', 'Saved', 'Existing request.request.json'), 'utf8')).request.url).toBe('https://example.test/saved')
    await page.keyboard.press('ControlOrMeta+Shift+s')
    await expect(page.getByRole('dialog', { name: /Save request/i })).toBeVisible()
    await page.keyboard.press('Escape')
    await openShortcuts(page)
    await edit(page, 'Search Sidebar', 'Backspace')
    await edit(page, 'Zoom In', 'ControlOrMeta+KeyF')
    await edit(page, 'Toggle Two-Pane View', 'ControlOrMeta+Alt+Shift+KeyV')
    await page.keyboard.press('Escape')
    const zoom = () => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.getZoomLevel())
    const before = await zoom()
    await page.keyboard.press('ControlOrMeta+=')
    expect(await zoom()).toBe(before)
    await page.getByRole('tab', { name: 'Body', exact: true }).first().click()
    await page.getByLabel('Body type', { exact: true }).selectOption('raw')
    await page.getByLabel('Request body').focus()
    // The reassigned app command must win over CodeMirror's built-in Find binding.
    await page.keyboard.press('ControlOrMeta+KeyF')
    await expect.poll(zoom).toBe(before + 0.5)
    await expect(page.locator('.cm-search')).toHaveCount(0)
    await page.keyboard.press('ControlOrMeta+0')
    await page.keyboard.press('ControlOrMeta+Alt+Shift+KeyV')
    const req = await page.locator('.editor').boundingBox(), res = await page.locator('.response').boundingBox()
    expect(res!.x).toBeGreaterThan(req!.x)
    expect(Math.abs(res!.y - req!.y)).toBeLessThan(3)
    await page.keyboard.press('ControlOrMeta+Alt+KeyV')
    expect((await page.locator('.response').boundingBox())!.x).toBeGreaterThan((await page.locator('.editor').boundingBox())!.x)
  } finally { await app.close() }
})

test('custom sidebar bindings are scoped to tree focus and disabled shortcuts stop zoom', async () => {
  const root = await mkdtemp(join(tmpdir(), 'pm-sidebar-keys-'))
  const launch = () => electron.launch({ args: ['.'], env: { ...process.env, PM_LOCAL_USER_DATA: join(root, 'appdata') } })
  let app = await launch()
  try {
    let page = await app.firstWindow()
    await app.evaluate(({ dialog }, dir) => { dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [dir] })) as typeof dialog.showOpenDialog }, root)
    await page.getByRole('button', { name: 'Open an existing workspace folder…' }).click()
    await expect(page.getByRole('button', { name: 'Create new', exact: true })).toBeVisible()
    await page.evaluate(async () => {
      const { id } = await window.api.createCollection('Keys')
      const folder = await window.api.createFolder(id, 'Nested')
      await window.api.createRequest(folder.id, 'Leaf')
    })
    await app.close()
    app = await launch(); page = await app.firstWindow()
    await openShortcuts(page)
    await edit(page, 'Rename Item', 'ControlOrMeta+Alt+Shift+KeyE')
    await page.keyboard.press('Escape')
    const collection = page.getByRole('treeitem').filter({ hasText: 'Keys' }).first()
    await collection.focus()
    await page.keyboard.press('Alt+ArrowRight')
    await expect(page.getByRole('treeitem').filter({ hasText: 'Leaf' })).toBeVisible()
    await collection.focus()
    await page.keyboard.press('ControlOrMeta+e')
    await expect(page.locator('.rename-input')).toHaveCount(0)
    await page.keyboard.press('ControlOrMeta+Alt+Shift+KeyE')
    await expect(page.locator('.rename-input')).toBeVisible()
    await page.keyboard.press('Escape')
    await openShortcuts(page)
    await page.getByRole('switch', { name: 'Keyboard Shortcuts', exact: true }).click()
    await page.keyboard.press('Escape')
    const before = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.getZoomLevel())
    await page.keyboard.press('ControlOrMeta+=')
    expect(await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.getZoomLevel())).toBe(before)
    await collection.focus()
    await page.keyboard.press('ControlOrMeta+Alt+Shift+KeyE')
    await expect(page.locator('.rename-input')).toHaveCount(0)
  } finally { await app.close() }
})
