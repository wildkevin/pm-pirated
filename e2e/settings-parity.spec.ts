import { _electron as electron, expect, test } from '@playwright/test'
import { mkdtemp, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

test('Postman preferences apply live and survive restart', async () => {
  const root = await mkdtemp(join(tmpdir(), 'pm-preferences-'))
  const userData = join(root, 'appdata')
  const launch = () => electron.launch({ args: ['.'], env: { ...process.env, PM_LOCAL_USER_DATA: userData } })
  let app = await launch()
  try {
    let page = await app.firstWindow()
    await app.evaluate(({ dialog }, dir) => { dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [dir] })) as typeof dialog.showOpenDialog }, root)
    await page.getByRole('button', { name: 'Open an existing workspace folder…' }).click()
    await page.getByRole('button', { name: 'New request tab', exact: true }).click()
    await page.getByRole('button', { name: 'Settings', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'SETTINGS', exact: true })
    await dialog.getByLabel('HTTP version', { exact: true }).selectOption('http1')
    await dialog.getByLabel('Font Size (px)').fill('18')
    await dialog.getByLabel('Indentation count').fill('3')
    await dialog.getByRole('switch', { name: 'Auto close quotes', exact: true }).click()
    await dialog.getByRole('switch', { name: 'Show icons with tab names', exact: true }).click()
    await dialog.getByRole('tab', { name: 'Themes', exact: true }).click()
    await dialog.getByLabel('Theme selection').selectOption('manual')
    await dialog.getByLabel('Theme', { exact: true }).selectOption('Dracula')
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'Dracula')
    await expect(page.locator('html')).toHaveCSS('color-scheme', 'dark')
    await page.screenshot({ path: '.qa/settings-themes.png' })
    await page.keyboard.press('Escape')
    await expect(page.locator('.tabs .method-get')).toHaveCount(0)
    await page.getByRole('tab', { name: 'Body', exact: true }).first().click()
    await page.getByLabel('Body type', { exact: true }).selectOption('raw')
    const editor = page.locator('.code-editor .cm-content').first()
    await expect(page.locator('.code-editor .cm-editor').first()).toHaveCSS('font-size', '18px')
    await editor.fill('')
    await editor.pressSequentially('"')
    await expect(editor).toHaveText('"')
    await editor.fill('')
    await editor.pressSequentially('{')
    await expect(editor).toHaveText('{}')
    await editor.press('Enter')
    expect(await editor.innerText()).toContain('\n   \n')
    await page.getByRole('button', { name: 'Settings', exact: true }).click()
    await page.getByRole('tab', { name: 'General', exact: true }).click()
    await page.screenshot({ path: '.qa/settings-general.png' })
    await expect.poll(async () => JSON.parse(await readFile(join(userData, 'settings.json'), 'utf8')).editor.fontSize).toBe(18)
    await app.close()
    app = await launch()
    page = await app.firstWindow()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'Dracula')
    await page.getByRole('button', { name: 'Settings', exact: true }).click()
    await expect(page.getByLabel('Font Size (px)')).toHaveValue('18')
    await expect(page.getByLabel('HTTP version', { exact: true })).toHaveValue('http1')
  } finally { await app.close() }
})

test('system themes, sidebar preferences, autocomplete and autosave take effect', async () => {
  const root = await mkdtemp(join(tmpdir(), 'pm-behavior-'))
  const launch = () => electron.launch({ args: ['.'], env: { ...process.env, PM_LOCAL_USER_DATA: join(root, 'appdata') } })
  let app = await launch()
  try {
    let page = await app.firstWindow()
    await app.evaluate(({ dialog }, dir) => { dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [dir] })) as typeof dialog.showOpenDialog }, root)
    await page.getByRole('button', { name: 'Open an existing workspace folder…' }).click()
    await expect(page.getByRole('button', { name: 'Create new', exact: true })).toBeVisible()
    await page.evaluate(async () => {
      const { id } = await window.api.createCollection('Preferences')
      await window.api.createRequest(id, 'First')
      await window.api.createRequest(id, 'Second')
      await window.api.saveVariables('globals', [{ key: 'serverBase', initial: 'http://localhost', current: 'http://localhost', enabled: true, type: 'default' }])
    })
    await app.close()
    app = await launch()
    page = await app.firstWindow()
    await page.emulateMedia({ colorScheme: 'light' })
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'Light')
    await page.emulateMedia({ colorScheme: 'dark' })
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'Dark')
    await page.getByRole('button', { name: 'Settings', exact: true }).click()
    await page.getByRole('switch', { name: 'Always open sidebar item in new tab', exact: true }).click()
    await page.getByRole('switch', { name: 'Autosave', exact: true }).click()
    await page.keyboard.press('Escape')
    const collection = page.getByRole('treeitem').filter({ hasText: 'Preferences' }).first()
    await collection.dblclick()
    await page.getByRole('treeitem').filter({ hasText: 'First' }).last().click()
    await page.getByRole('treeitem').filter({ hasText: 'Second' }).last().click()
    await expect(page.locator('.tabs .tab')).toHaveCount(3)
    await expect(page.locator('.tabs .preview')).toHaveCount(0)
    const url = page.getByLabel('Request URL')
    await url.fill('{{server')
    await expect(page.locator('.cm-tooltip-autocomplete')).toContainText('serverBase')
    await page.keyboard.press('Escape')
    await url.fill('http://localhost/saved-by-preference')
    await expect.poll(async () => {
      const ws = await page.evaluate(() => window.api.refreshWorkspace())
      const request = ws.collections[0].children!.find(c => c.name === 'Second')!
      return page.evaluate(id => window.api.readRequest(id), request.id)
    }).toMatchObject({ request: { url: 'http://localhost/saved-by-preference' } })
    await page.getByRole('button', { name: 'Settings', exact: true }).click()
    await page.getByRole('switch', { name: 'Two-pane view', exact: true }).click()
    await page.getByRole('switch', { name: 'Swap left and right sidebars', exact: true }).click()
    await page.keyboard.press('Escape')
    const request = await page.locator('.editor').boundingBox(), response = await page.locator('.response').boundingBox()
    expect(response!.x).toBeGreaterThan(request!.x)
    expect(Math.abs(response!.y - request!.y)).toBeLessThan(3)
    const sidebar = await page.locator('.sidebar').boundingBox()
    expect(sidebar!.x).toBeGreaterThan(request!.x)
  } finally { await app.close() }
})
