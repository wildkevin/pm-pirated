import { _electron as electron, expect, test, type Page } from '@playwright/test'
import { mkdtemp } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const focusedInsideDialog = (page: Page) => page.evaluate(() => !!document.activeElement?.closest('[role="dialog"]'))

test('settings focus, editable numbers, proxy dependency, and certificate controls', async () => {
  const userData = await mkdtemp(join(tmpdir(), 'pml-settings-qa-'))
  const app = await electron.launch({ args: ['.'], env: { ...process.env, PM_LOCAL_USER_DATA: userData } })
  try {
    const page = await app.firstWindow()
    const gear = page.getByRole('button', { name: 'Settings', exact: true })
    await gear.click()
    await expect(page.getByRole('dialog', { name: 'SETTINGS', exact: true })).toBeVisible()
    expect(await focusedInsideDialog(page)).toBe(true)
    for (let i = 0; i < 25; i++) { await page.keyboard.press('Tab'); expect(await focusedInsideDialog(page)).toBe(true) }
    const timeout = page.getByLabel('Request timeout in ms')
    await timeout.fill('')
    await expect(timeout).toHaveValue('')
    await timeout.pressSequentially('2500')
    await expect(timeout).toHaveValue('2500')
    await page.getByRole('tab', { name: 'Proxy', exact: true }).click()
    await page.getByLabel('Respect HTTP_PROXY', { exact: false }).check()
    await page.getByLabel('Use the system proxy', { exact: true }).uncheck()
    await expect(page.getByLabel('Respect HTTP_PROXY', { exact: false })).toBeDisabled()
    await page.getByLabel('Add a custom proxy configuration', { exact: true }).check()
    const port = page.getByLabel('Proxy port', { exact: true })
    await port.fill('')
    await expect(port).toHaveValue('')
    await port.pressSequentially('3128')
    await expect(port).toHaveValue('3128')
    await port.fill('70000')
    await expect(port).toHaveAttribute('aria-invalid', 'true')
    expect(await port.evaluate((input) => (input as HTMLInputElement).validity.valid)).toBe(false)
    await page.getByLabel('Proxy host', { exact: true }).focus()
    await expect(port).toHaveValue('3128')
    await page.getByRole('tab', { name: 'Certificates', exact: true }).click()
    await expect(page.getByText('Uses the operating system’s trusted certificate store', { exact: false })).toBeVisible()
    await page.getByRole('button', { name: 'Add Certificate', exact: true }).click()
    const host = page.getByLabel('Certificate host', { exact: true })
    await host.fill('https://localhost:8443')
    await expect(host).toHaveValue('localhost:8443')
    await host.fill('localhost:70000')
    await expect(page.getByRole('alert')).toContainText('Enter a hostname')
    await page.getByRole('tab', { name: 'Certificates', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    await expect(page.getByRole('tab', { name: 'Proxy', exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(gear).toBeFocused()
    const menu = await app.evaluate(({ Menu, app }) => ({ name: app.getName(), items: JSON.stringify(Menu.getApplicationMenu()?.items.map((item) => ({ label: item.label, submenu: item.submenu?.items.map((i) => i.role) }))) }))
    expect(menu.name).toBe('PM Local')
    expect(menu.items).not.toContain('"close"')
    expect(menu.items).not.toContain('reload')
  } finally { await app.close() }
})

test('menus keep duplicate labels distinct and support arrow keys and focus restoration', async () => {
  const userData = await mkdtemp(join(tmpdir(), 'pml-menu-qa-'))
  const workspace = await mkdtemp(join(tmpdir(), 'pml-menu-ws-'))
  const app = await electron.launch({ args: ['.'], env: { ...process.env, PM_LOCAL_USER_DATA: userData } })
  try {
    const page = await app.firstWindow()
    await app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = (async () => ({ canceled: false, filePaths: [path] })) as typeof dialog.showOpenDialog }, workspace)
    await page.getByRole('button', { name: 'Open an existing workspace folder…' }).click()
    const create = page.getByRole('button', { name: 'Create new', exact: true })
    await create.focus()
    await page.keyboard.press('Enter')
    await page.keyboard.press('ArrowDown')
    await expect(page.getByRole('menuitem').first()).toBeFocused()
    await page.keyboard.press('ArrowDown')
    await expect(page.getByRole('menuitem').nth(1)).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(create).toBeFocused()
    for (let i = 0; i < 4; i++) await page.getByRole('button', { name: 'New request tab', exact: true }).click()
    const tabs = page.getByRole('button', { name: 'Open tabs', exact: true })
    await tabs.click()
    await expect(page.getByRole('menuitem')).toHaveCount(4)
    const search = page.getByLabel('Search menu')
    await search.fill('zz')
    await expect(page.getByRole('menuitem')).toHaveCount(0)
    await expect(page.getByText('No results', { exact: true })).toBeVisible()
    await search.fill('Untitled')
    await expect(page.getByRole('menuitem')).toHaveCount(4)
    await search.fill('zz')
    await expect(page.getByRole('menuitem')).toHaveCount(0)
    await page.keyboard.press('Escape')
    await expect(tabs).toBeFocused()
  } finally { await app.close() }
})
